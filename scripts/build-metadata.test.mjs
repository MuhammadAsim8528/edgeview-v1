import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
import { sourceDigest, artifactDigest, readBuildIdentity } from '../shared/build_identity.mjs';
import { writeBuildMetadata } from './build-metadata.mjs';
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'edgeview-build-id-'));
try {
  fs.mkdirSync(path.join(root, 'src')); fs.mkdirSync(path.join(root, 'dist'));
  fs.writeFileSync(path.join(root, 'package.json'), JSON.stringify({ name: 'edgeview', version: '1.0.0' }));
  fs.writeFileSync(path.join(root, 'src', 'fixture.ts'), 'source-one');
  fs.writeFileSync(path.join(root, 'dist', 'server.cjs'), 'backend-one');
  fs.writeFileSync(path.join(root, 'dist', 'index.html'), 'frontend-one');
  assert.equal(readBuildIdentity(root).available, false);
  const first = writeBuildMetadata(root, 'a'.repeat(40));
  assert.equal(readBuildIdentity(root).buildId, first.buildId);
  assert.equal(artifactDigest(root), first.artifactHash, 'metadata must not hash itself');
  assert.equal(writeBuildMetadata(root).buildId, first.buildId, 'timestamp/git availability are not code identity');
  fs.utimesSync(path.join(root, 'src/fixture.ts'), new Date(0), new Date(0));
  assert.equal(sourceDigest(root), first.sourceHash, 'timestamps alone do not change code identity');
  fs.writeFileSync(path.join(root, 'src/fixture.ts'), 'source-two');
  assert.notEqual(sourceDigest(root), first.sourceHash);
  const second = writeBuildMetadata(root);
  assert.notEqual(second.buildId, first.buildId);
  fs.writeFileSync(path.join(root, 'dist/server.cjs'), 'backend-two');
  assert.notEqual(artifactDigest(root), second.artifactHash, 'changed artifacts must be detectable');
  const file = path.join(root, 'dist/build-info.json');
  fs.writeFileSync(file, JSON.stringify({ ...second, secret: 'must-not-leak' }));
  assert.ok(!JSON.stringify(readBuildIdentity(root)).includes('must-not-leak'));
  fs.writeFileSync(file, JSON.stringify({ ...second, buildId: 'b'.repeat(64) }));
  assert.equal(readBuildIdentity(root).available, false);
  const temporary = `${file}.${process.pid}.tmp`;
  fs.writeFileSync(temporary, 'pre-existing temporary file');
  assert.throws(() => writeBuildMetadata(root));
  assert.equal(fs.readFileSync(temporary, 'utf8'), 'pre-existing temporary file'); fs.unlinkSync(temporary);
  fs.writeFileSync(file, 'x'.repeat(17000)); assert.equal(readBuildIdentity(root).available, false);
  fs.symlinkSync(path.join(root, 'missing-link-target'), path.join(root, 'src', 'dangling-link'), 'junction');
  assert.throws(() => sourceDigest(root), /symbolic links/, 'dangling links must not be silently skipped');
  console.log('PASS content-based build identity, stale source/artifacts, unknown metadata and safe projection');
} finally { fs.rmSync(root, { recursive: true, force: true }); }
