import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { runDoctor as doctor } from './doctor.mjs';
const runDoctor = options => doctor({ ...options, environment: {} });
import { writeBuildMetadata } from './build-metadata.mjs';
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'edgeview-doctor-'));
try {
  fs.writeFileSync(path.join(root, 'package.json'), JSON.stringify({ name: 'edgeview', version: '1.0.0', dependencies: {} }));
  fs.writeFileSync(path.join(root, 'package-lock.json'), JSON.stringify({ name: 'edgeview', version: '1.0.0', packages: { '': { dependencies: {} } } }));
  fs.mkdirSync(path.join(root, 'dist')); fs.writeFileSync(path.join(root, 'dist/server.cjs'), ''); fs.writeFileSync(path.join(root, 'dist/index.html'), '');
  let calls = 0;
  const request = async url => { calls++; assert.equal(url, 'http://127.0.0.1:3901/api/health'); return Response.json({ status: 'ok', app: { name: 'edgeview', project_root: root }, database: { status: 'ok' }, providers: { serper: { enabled: true, configured: true } }, secret: 'must-not-leak' }); };
  const healthy = await runDoctor({ root, request });
  assert.equal(healthy.exitCode, 0); assert.equal(calls, 1);
  assert.ok(!JSON.stringify(healthy).includes('must-not-leak'));
  assert.equal(healthy.checks.find(check => check.id === 'provider_serper').status, 'WARN');
  assert.equal(healthy.checks.find(check => check.id === 'resources').status, 'WARN', 'old runtime cannot fabricate resource measurements');
  const wrongStorage = await runDoctor({ root, request: async () => Response.json({ status: 'ok', app: { name: 'edgeview', project_root: root, data_root: path.join(root, 'other') } }) });
  assert.equal(wrongStorage.checks.find(check => check.id === 'running_storage').status, 'FAIL');
  const measured = await runDoctor({ root, request: async () => Response.json({ status: 'ok', app: { name: 'edgeview', project_root: root }, database: { status: 'ok' }, resources: { status: 'PASS', rssBytes: 1, cpuPercent: 0, systemTotalBytes: 2, diskAvailableBytes: 3 } }) });
  assert.equal(measured.checks.find(check => check.id === 'database').status, 'WARN', 'legacy projection-only health must not certify the operational DB');
  const unhealthyDb = await runDoctor({ root, request: async () => Response.json({ status: 'ok', app: { name: 'edgeview', project_root: root }, database: { status: 'degraded', operational: { status: 'degraded' } } }) });
  assert.equal(unhealthyDb.checks.find(check => check.id === 'database').status, 'FAIL');
  assert.equal(measured.checks.find(check => check.id === 'resources').status, 'PASS');
  // Installation identity: absent warns without failing the doctor, a valid UUID v4
  // passes, and a corrupt file fails because the operator cannot trust correlation.
  assert.equal(healthy.checks.find(check => check.id === 'device_identity').status, 'WARN', 'fresh install has no identity file yet');
  const identityPath = path.join(root, 'data', 'installation.json');
  fs.mkdirSync(path.dirname(identityPath));
  fs.writeFileSync(identityPath, JSON.stringify({ installation_id: '00000000-0000-4000-8000-000000000001' }));
  const withIdentity = await runDoctor({ root, request });
  assert.equal(withIdentity.checks.find(check => check.id === 'device_identity').status, 'PASS');
  assert.equal(withIdentity.exitCode, 0);
  fs.writeFileSync(identityPath, JSON.stringify({ installation_id: 'hardware-derived-or-corrupt' }));
  const badIdentity = await runDoctor({ root, request });
  assert.equal(badIdentity.checks.find(check => check.id === 'device_identity').status, 'FAIL');
  assert.equal(badIdentity.exitCode, 1);
  fs.unlinkSync(identityPath);
  const commands = [];
  const full = await runDoctor({ root, request, full: true, execute: command => { commands.push(command); return { status: command === 'build' ? 1 : 0 }; } });
  assert.equal(full.exitCode, 1); assert.deepEqual(commands, ['check', 'build']);
  const offline = await runDoctor({ root, request: async () => { throw new Error('secret-api-key'); } });
  assert.equal(offline.exitCode, 1); assert.ok(!JSON.stringify(offline).includes('secret-api-key'));
  const wrongRoot = await runDoctor({ root, request: async () => Response.json({ status: 'ok', app: { name: 'edgeview', project_root: `${root}-other` } }) });
  assert.equal(wrongRoot.exitCode, 1);
  const oversized = await runDoctor({ root, request: async () => new Response('x'.repeat(300000)) }); assert.equal(oversized.exitCode, 1);
  const thrown = await runDoctor({ root, request, full: true, execute: () => { throw new Error('private-error'); } });
  assert.equal(thrown.exitCode, 1); assert.ok(!JSON.stringify(thrown).includes('private-error'));
  const identity = writeBuildMetadata(root);
  const identified = buildId => async () => Response.json({ status: 'ok', app: { name: 'edgeview', project_root: root, build: { available: true, buildId } }, database: { status: 'ok' } });
  const same = await runDoctor({ root, request: identified(identity.buildId) });
  assert.equal(same.checks.find(check => check.id === 'build_freshness').status, 'PASS');
  assert.equal(same.checks.find(check => check.id === 'running_build').status, 'PASS');
  const old = await runDoctor({ root, request: identified('f'.repeat(64)) });
  assert.equal(old.exitCode, 1); assert.equal(old.checks.find(check => check.id === 'running_build').status, 'FAIL');
  fs.writeFileSync(path.join(root, 'server.ts'), 'changed after build');
  const changed = await runDoctor({ root, request: identified(identity.buildId) });
  assert.equal(changed.checks.find(check => check.id === 'build_freshness').status, 'FAIL');
  fs.writeFileSync(path.join(root, 'package-lock.json'), '{}');
  const badLock = await runDoctor({ root, request }); assert.equal(badLock.exitCode, 1);
  console.log('PASS doctor states, locked dependencies, offline failure, safe output and full-check orchestration');
} finally { fs.rmSync(root, { recursive: true, force: true }); }
